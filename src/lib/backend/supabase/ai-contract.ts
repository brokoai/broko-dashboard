import { JOB_ID_RE, isValidJobId, type JobClaim, type JobRecord } from "@/lib/ai-brain/jobs";
import { ProcessedMessageSchema, type ErrorCategory, type JobStatus, type MessageRef, type ProcessedMessage } from "@/lib/ai-brain/schema";
import { isValidReviewId } from "@/lib/ai-brain/view";

/**
 * The CONTRACT between the application and the proposed AI migrations (0003 and 0004): how rows become application objects and how
 * application values become RPC arguments. These are pure functions. They are NOT a Supabase repository, they call nothing, and
 * no code in this app uses them yet; they exist so the future repository has one reviewed place for these rules, and so tests can
 * hold them against the SQL text. Contract tests are not integration tests: nothing here proves behaviour on a real database.
 *
 * The rules:
 *  - `review_id` is AUTHORITATIVE in the database. A repository inserts a message WITHOUT it (the column default generates it) and
 *    always reads it back; it never derives one from a dedupe key (`reviewIdFor` is for the in-memory demo only).
 *  - The public JOB ID is `ai_jobs.correlation_id` (12 hex characters, = jobId(ref)). A JobRecord's `id` is that value. The row's
 *    internal uuid `id` is never read, sent or shown.
 *  - Timestamps leave PostgREST as "2026-10-12T10:00:00.123456+00:00"; the application schema wants UTC "Z" strings.
 */

type Row = Record<string, unknown>;

/** Re-expresses a database timestamp as a UTC ISO string; null stays null; anything unparseable is an error, not a silent null. */
export function isoUtc(v: unknown): string | null {
  if (v === null || v === undefined) return null;
  if (typeof v !== "string") throw new Error("timestamp is not a string");
  const ms = Date.parse(v);
  if (Number.isNaN(ms)) throw new Error("timestamp is not valid");
  return new Date(ms).toISOString();
}
const need = (v: unknown): string => {
  const s = isoUtc(v);
  if (s === null) throw new Error("required timestamp is null");
  return s;
};

/** The ai_messages columns a server-side repository reads (all of them; this never reaches a browser, see view.ts). */
export const AI_MESSAGE_COLUMNS = [
  "dedupe_key", "review_id", "provider", "source_message_id", "internet_message_id", "mailbox_ref", "received_at", "sender_name",
  "sender_email", "subject", "excerpt", "status", "analysis", "classifier", "grounding_notes", "risk_flags", "owner", "review_reasons",
  "proposed_priority", "proposed_due_at", "task_id", "notification", "reviewed_by", "reviewed_at", "confirmed_owner", "error",
  "created_at", "updated_at",
] as const;

/** An ai_messages row -> ProcessedMessage. Uses the PERSISTED review_id; a row without a valid one is an error. */
export function recordFromRow(row: Row): ProcessedMessage {
  if (!isValidReviewId(row.review_id)) throw new Error("ai_messages row has no valid review_id (it is generated by the database and must be read back)");
  const confirmed = row.confirmed_owner as { confirmed_at?: unknown } | null;
  return ProcessedMessageSchema.parse({
    ...row,
    received_at: need(row.received_at),
    proposed_due_at: isoUtc(row.proposed_due_at),
    reviewed_at: isoUtc(row.reviewed_at),
    created_at: need(row.created_at),
    updated_at: need(row.updated_at),
    confirmed_owner: confirmed ? { ...confirmed, confirmed_at: need(confirmed.confirmed_at) } : null,
  });
}

/** ProcessedMessage -> the columns to INSERT. `review_id` is left out on purpose: the database generates it. */
export function messageInsertFromRecord(r: ProcessedMessage): Omit<ProcessedMessage, "review_id"> {
  const { review_id: _generatedByTheDatabase, ...rest } = r; // eslint-disable-line @typescript-eslint/no-unused-vars
  return rest;
}

const jobRef = (row: Row): MessageRef => ({ provider: row.provider as MessageRef["provider"], mailbox_ref: String(row.mailbox_ref), source_message_id: String(row.source_message_id) });

/** An ai_jobs row -> JobRecord. `id` is the PUBLIC job id (correlation_id); the row's internal uuid is ignored. */
export function jobFromRow(row: Row): JobRecord {
  if (!isValidJobId(row.correlation_id)) throw new Error("ai_jobs row has no valid correlation_id");
  return {
    id: row.correlation_id, ref: jobRef(row), status: row.status as JobStatus, attempts: Number(row.attempts), max_attempts: Number(row.max_attempts),
    next_attempt_at: need(row.next_attempt_at), lease_owner: (row.lease_owner as string | null) ?? null, lease_expires_at: isoUtc(row.lease_expires_at),
    workflow_id: (row.workflow_id as string | null) ?? null, outcome: (row.outcome as string | null) ?? null,
    error_category: (row.error_category as ErrorCategory | null) ?? null, audit_failed: Boolean(row.audit_failed),
    requeued_by: (row.requeued_by as string | null) ?? null, requeued_at: isoUtc(row.requeued_at),
    enqueued_at: need(row.enqueued_at), started_at: isoUtc(row.started_at), finished_at: isoUtc(row.finished_at), updated_at: need(row.updated_at),
  };
}

// ---- RPC arguments. Names are exactly the SQL parameter names (tests compare them with the SQL text). ----
const requireJobId = (id: string): string => {
  if (!isValidJobId(id)) throw new Error(`job id must match ${JOB_ID_RE}`);
  return id;
};
const requireReviewId = (id: string): string => {
  if (!isValidReviewId(id)) throw new Error("review id must be a lower-case UUID");
  return id;
};

export const enqueueArgs = (ref: MessageRef, maxAttempts?: number) => ({
  p_provider: ref.provider, p_mailbox_ref: ref.mailbox_ref, p_source_message_id: ref.source_message_id,
  ...(maxAttempts === undefined ? {} : { p_max_attempts: maxAttempts }),
});
export const claimArgs = (worker: string, leaseSeconds: number) => ({ p_worker: worker, p_lease_seconds: leaseSeconds });
export const completeArgs = (c: JobClaim, workflowId: string | null, outcome: string, auditFailed: boolean) => ({
  p_job_id: requireJobId(c.job.id), p_worker: c.worker_id, p_attempt: c.attempt, p_workflow_id: workflowId, p_outcome: outcome, p_audit_failed: auditFailed,
});
export const retryArgs = (c: JobClaim, error: ErrorCategory, runAt: Date, workflowId: string | null, auditFailed: boolean) => ({
  p_job_id: requireJobId(c.job.id), p_worker: c.worker_id, p_attempt: c.attempt, p_error: error, p_run_at: runAt.toISOString(),
  p_workflow_id: workflowId, p_audit_failed: auditFailed,
});
export const failArgs = (c: JobClaim, error: ErrorCategory, workflowId: string | null, auditFailed: boolean) => ({
  p_job_id: requireJobId(c.job.id), p_worker: c.worker_id, p_attempt: c.attempt, p_error: error, p_workflow_id: workflowId, p_audit_failed: auditFailed,
});
export const requeueArgs = (jobId: string) => ({ p_job_id: requireJobId(jobId) });
export const approveArgs = (reviewId: string, v: { title: string; description: string | null; assigned_to: string | null; due_at: string | null; priority: string | null }) => ({
  p_review_id: requireReviewId(reviewId), p_title: v.title, p_description: v.description, p_assigned_to: v.assigned_to, p_due_at: v.due_at, p_priority: v.priority,
});
export const rejectArgs = (reviewId: string) => ({ p_review_id: requireReviewId(reviewId) });
