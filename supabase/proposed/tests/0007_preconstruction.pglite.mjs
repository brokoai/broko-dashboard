// LOCAL ONLY. Executes 0007_preconstruction.proposed.sql on a local PostgreSQL (PGlite) that imitates Supabase's roles, and
// checks the access rules the Pre-Construction Advisor depends on. Never connects to any remote database. Does NOT prove the
// same on a real Supabase project (Storage in particular is a stub here: only storage.buckets / storage.objects exist).
//   npm install --no-save @electric-sql/pglite
//   node supabase/proposed/tests/0007_preconstruction.pglite.mjs
import { fileURLToPath } from "node:url";
import { IDS, createEnv } from "./lib/pglite_env.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url)); // supabase/
const env = await createEnv();
const { db, check, attempt, denied } = env;

// Minimal stand-in for Supabase Storage (the real schema is far larger; the policies only need these two tables).
await db.exec(`
  create schema storage;
  create table storage.buckets (id text primary key, name text, public boolean not null default false, file_size_limit bigint, allowed_mime_types text[]);
  create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text not null references storage.buckets (id), name text not null);
  alter table storage.objects enable row level security;
  grant usage on schema storage to anon, authenticated, service_role;
  grant select, insert, update, delete on storage.objects to authenticated;
  grant select on storage.buckets to authenticated;
`);

const applied = await env.apply([`${root}migrations/0001_init.sql`, `${root}proposed/0007_preconstruction.proposed.sql`]);
if (applied) {
  await env.seedUsers();
  let P1 = ""; // active project (ids are generated by the database: the API has no INSERT privilege on projects.id)
  let P2 = ""; // archived project
  const D1 = "20000000-0000-0000-0000-000000000001";
  const D2 = "20000000-0000-0000-0000-000000000002";

  // ---- writes: administrators only ------------------------------------------------------------------------------
  const insProject = (name) => attempt("authenticated", IDS.admin, "insert into public.precon_projects (name, developer, city, status, created_by) values ($1, 'Acme', 'Toronto', 'selling', $2) returning id", [name, IDS.admin]);
  const r1 = await insProject("Lakeview Towers");
  const r2 = await insProject("Old Mill");
  check("an administrator can create a project", r1.ok, r1.msg);
  check("an administrator can create a second project", r2.ok, r2.msg);
  P1 = r1.rows[0].id; P2 = r2.rows[0].id;
  const path1 = `projects/${P1}/${D1}/brochure.pdf`;
  const path2 = `projects/${P2}/${D2}/plan.pdf`;
  const mProject = await attempt("authenticated", IDS.m1, "insert into public.precon_projects (name, created_by) values ('x', $1)", [IDS.m1]);
  check("a member cannot create a project (row level security)", denied(mProject), mProject.msg);
  const forged = await attempt("authenticated", IDS.admin, "insert into public.precon_projects (name, created_by) values ('x', $1)", [IDS.m1]);
  check("an administrator cannot forge created_by", denied(forged), forged.msg);
  check("an administrator archives a project", (await attempt("authenticated", IDS.admin, "update public.precon_projects set archived_at = now() where id = $1 returning id", [P2])).n === 1);
  const mUpd = await attempt("authenticated", IDS.m1, "update public.precon_projects set name = 'hacked' where id = $1 returning id", [P1]);
  check("a member cannot edit a project (zero rows)", mUpd.ok && mUpd.n === 0);
  const colUpd = await attempt("authenticated", IDS.admin, "update public.precon_projects set created_by = $1 where id = $2", [IDS.m1, P1]);
  check("created_by is not updatable even by an administrator", denied(colUpd), colUpd.msg);
  const del = await attempt("authenticated", IDS.admin, "delete from public.precon_projects where id = $1", [P1]);
  check("projects cannot be deleted through the API (archive instead)", denied(del), del.msg);

  // ---- reads ----------------------------------------------------------------------------------------------------
  const mRead = await attempt("authenticated", IDS.m1, "select id from public.precon_projects order by name");
  check("a member sees active projects only", mRead.ok && mRead.rows.length === 1 && mRead.rows[0].id === P1, mRead.msg);
  const aRead = await attempt("authenticated", IDS.admin, "select id from public.precon_projects");
  check("an administrator also sees archived projects", aRead.ok && aRead.rows.length === 2);
  const anon = await attempt("anon", null, "select id from public.precon_projects");
  check("anon cannot read projects", denied(anon), anon.msg);

  // ---- documents, storage, chunks -------------------------------------------------------------------------------
  const insDoc = (id, pid, path, who = IDS.admin, extra = "") => attempt("authenticated", who, `insert into public.precon_documents (id, project_id, title, filename, kind, mime_type, size_bytes, storage_path, uploaded_by) values ($1, $2, 'Doc', 'brochure.pdf', 'brochure', 'application/pdf', ${extra || "1000"}, $3, $4) returning id`, [id, pid, path, who]);
  check("an administrator registers a document (pending)", (await insDoc(D1, P1, path1)).ok);
  check("an administrator registers a document on the archived project", (await insDoc(D2, P2, path2)).ok);
  const mDoc = await insDoc("20000000-0000-0000-0000-000000000009", P1, `projects/${P1}/20000000-0000-0000-0000-000000000009/x.pdf`, IDS.m1);
  check("a member cannot register a document", denied(mDoc), mDoc.msg);
  const big = await insDoc("20000000-0000-0000-0000-00000000000a", P1, `projects/${P1}/20000000-0000-0000-0000-00000000000a/x.pdf`, IDS.admin, "26214401");
  check("an oversized document row is refused by the database", !big.ok && big.code === "23514", big.msg);
  const badPath = await insDoc("20000000-0000-0000-0000-00000000000b", P1, `projects/${P1}/../../etc/passwd`);
  check("a path that is not projects/<id>/<id>/<safe name> is refused", !badPath.ok && badPath.code === "23514", badPath.msg);
  const dupPath = await insDoc("20000000-0000-0000-0000-00000000000c", P1, path1);
  check("two documents cannot share a storage path", !dupPath.ok && dupPath.code === "23505", dupPath.msg);
  const dir = await attempt("authenticated", IDS.admin, "update public.precon_documents set storage_path = 'projects/x' where id = $1", [D1]);
  check("storage_path is not updatable", denied(dir), dir.msg);
  const proj = await attempt("authenticated", IDS.admin, "update public.precon_documents set project_id = $1 where id = $2", [P2, D1]);
  check("a document cannot be moved to another project", denied(proj), proj.msg);
  const mDocRead = await attempt("authenticated", IDS.m1, "select id from public.precon_documents");
  check("a member sees documents of active projects only", mDocRead.ok && mDocRead.rows.length === 1 && mDocRead.rows[0].id === D1);

  const up = (who, name) => attempt("authenticated", who, "insert into storage.objects (bucket_id, name) values ('precon-files', $1) returning id", [name]);
  check("an administrator can upload to the path of a pending document", (await up(IDS.admin, path1)).ok);
  const stray = await up(IDS.admin, `projects/${P1}/20000000-0000-0000-0000-0000000000ff/stray.pdf`);
  check("an object with no pending document row is refused (no stray files)", denied(stray), stray.msg);
  const mUp = await up(IDS.m1, path1);
  check("a member cannot upload", denied(mUp), mUp.msg);
  check("the second administrator upload for the archived project works", (await up(IDS.admin, path2)).ok);
  const mObj = await attempt("authenticated", IDS.m1, "select name from storage.objects");
  check("a member can read the file of an active project only", mObj.ok && mObj.rows.length === 1 && mObj.rows[0].name === path1, mObj.msg);
  const bucket = await attempt("authenticated", IDS.m1, "select public, file_size_limit, allowed_mime_types from storage.buckets where id = 'precon-files'");
  check("the bucket is private, capped at 25 MB, and limited to known content types", bucket.rows?.[0]?.public === false && Number(bucket.rows[0].file_size_limit) === 26214400 && bucket.rows[0].allowed_mime_types.length === 7);
  const mDelObj = await attempt("authenticated", IDS.m1, "delete from storage.objects where name = $1 returning id", [path1]);
  check("a member cannot delete a stored file", mDelObj.ok && mDelObj.n === 0);

  const chunk = (who, id, did, pid, i, page, text) => attempt("authenticated", who, "insert into public.precon_chunks (document_id, project_id, chunk_index, page, content) values ($1, $2, $3, $4, $5) returning id", [did, pid, i, page, text]);
  check("an administrator stores extracted chunks", (await chunk(IDS.admin, null, D1, P1, 0, 3, "Two bedroom suites start from the twelfth floor with lake views and a rooftop pool.")).ok);
  check("a chunk on the archived project", (await chunk(IDS.admin, null, D2, P2, 0, 1, "Secret archived lake view lounge.")).ok);
  const wrongProj = await chunk(IDS.admin, null, D1, P2, 1, 1, "mismatched project");
  check("a chunk whose project does not match its document is refused", denied(wrongProj), wrongProj.msg);
  const mChunk = await chunk(IDS.m1, null, D1, P1, 5, 1, "member text");
  check("a member cannot write chunks", denied(mChunk), mChunk.msg);
  const dupIdx = await chunk(IDS.admin, null, D1, P1, 0, 1, "duplicate index");
  check("chunk_index is unique per document", !dupIdx.ok && dupIdx.code === "23505", dupIdx.msg);

  const search = (who, q, p = null) => attempt("authenticated", who, "select document_id, page, content from public.precon_search_chunks($1, $2, 8)", [q, p]);
  const s1 = await search(IDS.m1, "two bedroom lake view");
  check("full-text search returns the chunk with its document and page", s1.ok && s1.rows.length === 1 && s1.rows[0].document_id === D1 && s1.rows[0].page === 3, s1.msg);
  const s2 = await search(IDS.m1, "archived lounge");
  check("a member's search never returns chunks of an archived project", s2.ok && s2.rows.length === 0, s2.msg);
  const s3 = await search(IDS.admin, "archived lounge");
  check("an administrator's search can", s3.ok && s3.rows.length === 1);
  for (const bad of ['"', "&|!", "'; drop table x; --", "", "   "]) {
    const r = await search(IDS.m1, bad);
    check(`hostile or empty search text never raises (${JSON.stringify(bad)})`, r.ok, r.msg);
  }
  const sp = await search(IDS.m1, "pool", P2);
  check("search can be restricted to one project and still honours visibility", sp.ok && sp.rows.length === 0);
  check("anon cannot call the search function", denied(await attempt("anon", null, "select * from public.precon_search_chunks('pool')")));

  // ---- inventory ------------------------------------------------------------------------------------------------
  const inv = (who, unit, price = 799000) => attempt("authenticated", who, "insert into public.precon_inventory (project_id, unit_number, unit_type, bedrooms, bathrooms, area_sqft, price, availability, source, created_by) values ($1, $2, '2 Bed', 2, 2, 850, $3, 'available', 'manual', $4) returning id", [P1, unit, price, who]);
  check("an administrator adds inventory", (await inv(IDS.admin, "1204")).ok);
  const dupUnit = await inv(IDS.admin, "1204");
  check("a duplicate unit number in one project is refused", !dupUnit.ok && dupUnit.code === "23505", dupUnit.msg);
  const neg = await inv(IDS.admin, "1205", -1);
  check("a negative price is refused", !neg.ok && neg.code === "23514", neg.msg);
  const mInv = await inv(IDS.m1, "1206");
  check("a member cannot add inventory", denied(mInv), mInv.msg);
  const star = await attempt("authenticated", IDS.m1, "select * from public.precon_inventory");
  check("select * on inventory is refused for a member (unit_number is restricted)", denied(star), star.msg);
  const named = await attempt("authenticated", IDS.m1, "select unit_number from public.precon_inventory");
  check("a member cannot read unit_number", denied(named), named.msg);
  const cols = await attempt("authenticated", IDS.m1, "select id, project_id, unit_type, bedrooms, bathrooms, area_sqft, price, currency, availability, source, verified_at, updated_at from public.precon_inventory");
  check("a member can read every other inventory column", cols.ok && cols.rows.length === 1, cols.msg);
  const adminNum = await attempt("authenticated", IDS.admin, "select * from public.precon_unit_numbers()");
  check("an administrator reads unit numbers through the function", adminNum.ok && adminNum.rows.length === 1 && adminNum.rows[0].unit_number === "1204", adminNum.msg);
  const memNum = await attempt("authenticated", IDS.m1, "select * from public.precon_unit_numbers()");
  check("a member gets no unit numbers from the function", memNum.ok && memNum.rows.length === 0, memNum.msg);
  check("anon cannot call precon_unit_numbers", denied(await attempt("anon", null, "select * from public.precon_unit_numbers()")));
  const unitUpd = await attempt("authenticated", IDS.admin, "update public.precon_inventory set unit_number = '9999'");
  check("a unit number cannot be changed after creation", denied(unitUpd), unitUpd.msg);
  const priceUpd = await attempt("authenticated", IDS.admin, "update public.precon_inventory set price = 780000, availability = 'reserved' returning id");
  check("an administrator can update price and availability", priceUpd.ok && priceUpd.n === 1, priceUpd.msg);
  const mPriceUpd = await attempt("authenticated", IDS.m1, "update public.precon_inventory set price = 1 returning id");
  check("a member cannot change a price (zero rows)", mPriceUpd.ok && mPriceUpd.n === 0);
  const trunc = await attempt("authenticated", IDS.admin, "truncate public.precon_inventory");
  check("TRUNCATE is not available to authenticated", denied(trunc), trunc.msg);

  // ---- audit ----------------------------------------------------------------------------------------------------
  const aud = (who, actor) => attempt("authenticated", who, "insert into public.precon_audit (project_id, actor_id, action, entity, entity_id, detail) values ($1, $2, 'project.create', 'project', $1, '{\"n\":1}') returning id", [P1, actor]);
  check("an administrator records an audit event as themself", (await aud(IDS.admin, IDS.admin)).ok);
  check("an administrator cannot record an event as someone else", denied(await aud(IDS.admin, IDS.m1)));
  check("a member cannot record audit events", denied(await aud(IDS.m1, IDS.m1)));
  const mAud = await attempt("authenticated", IDS.m1, "select id from public.precon_audit");
  check("a member reads no audit events", mAud.ok && mAud.rows.length === 0);
  check("audit events cannot be updated", denied(await attempt("authenticated", IDS.admin, "update public.precon_audit set action = 'x'")));
  check("audit events cannot be deleted", denied(await attempt("authenticated", IDS.admin, "delete from public.precon_audit")));

  // ---- removal leaves no orphans --------------------------------------------------------------------------------
  const mDel = await attempt("authenticated", IDS.m1, "delete from public.precon_documents where id = $1 returning id", [D1]);
  check("a member cannot delete a document (zero rows)", mDel.ok && mDel.n === 0);
  // Order matters: the file must be removed WHILE its document row still exists (the storage read policy that DELETE ... RETURNING
  // needs is defined by that row). The application therefore removes the file first and the row second.
  const objDel = await attempt("authenticated", IDS.admin, "delete from storage.objects where name = $1 returning id", [path1]);
  check("an administrator can remove the stored file (while its row exists)", objDel.ok && objDel.n === 1, objDel.msg);
  const aDel = await attempt("authenticated", IDS.admin, "delete from public.precon_documents where id = $1 returning id", [D1]);
  const left = await db.query("select count(*)::int n from public.precon_chunks where document_id = $1", [D1]);
  check("deleting a document removes its chunks with it", aDel.ok && aDel.n === 1 && left.rows[0].n === 0, aDel.msg);
  const orphans = await db.query("select count(*)::int n from storage.objects o where o.bucket_id = 'precon-files' and not exists (select 1 from public.precon_documents d where d.storage_path = o.name) and o.name = $1", [path1]);
  check("no stored file is left without a document row", orphans.rows[0].n === 0);
}

const ok = env.print("0007 pre-construction (local PostgreSQL)");
process.exit(ok ? 0 : 1);
